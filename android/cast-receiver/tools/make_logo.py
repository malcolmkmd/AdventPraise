#!/usr/bin/env python3
"""Writes src/sda-logo.js: the church logo as an SVG path, from the iOS app's
SDALogoShape.swift (itself generated from Tools/source/sda-logo.svg), so the
TV draws exactly the outline iOS draws. Run again if the iOS shape changes:

    python3 -I tools/make_logo.py ../../AdventPraise/App/SDALogoShape.swift src/sda-logo.js
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
aspect = float(re.search(r"aspectRatio: CGFloat = ([0-9.]+)", text).group(1))
W, H = 1000 * aspect, 1000.0

def pt(x, y):
    return f"{float(x) * W:.1f} {float(y) * H:.1f}"

out = []
num = r"([0-9.]+)"
p = rf"p\({num}, {num}\)"
for line in text.splitlines():
    line = line.strip()
    if m := re.fullmatch(rf"path\.move\(to: {p}\)", line):
        out.append("M" + pt(*m.groups()))
    elif m := re.fullmatch(rf"path\.addCurve\(to: {p}, control1: {p}, control2: {p}\)", line):
        x, y, c1x, c1y, c2x, c2y = m.groups()
        out.append("C" + " ".join([pt(c1x, c1y), pt(c2x, c2y), pt(x, y)]))
    elif line == "path.closeSubpath()":
        out.append("Z")

d = "".join(out)
with open(dst, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_logo.py from the iOS app's SDALogoShape.swift. Don't edit.\n")
    f.write("// The Seventh-day Adventist church logo; fill it even-odd.\n")
    f.write(f"export const LOGO_ASPECT = {aspect};\n")
    f.write(f"export const LOGO_VIEWBOX = '0 0 {W:.1f} {H:.1f}';\n")
    f.write(f"export const LOGO_PATH = '{d}';\n")
print(f"{dst}: {len(d)} chars")
